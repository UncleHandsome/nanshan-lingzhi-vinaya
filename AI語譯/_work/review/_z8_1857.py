SHAPE = {"12c_中四下": (22, 43), "13a_下一": (62, 123)}


def main(dry=False):
    chunks = sorted(set(e[0] for e in E))
    before = {}
    for c in chunks:
        t, s = L.paras(c)
        ps = t.split(s)
        assert (len(ps), t.count("\n")) == SHAPE[c], (c, len(ps), t.count("\n"))
        assert "\r" not in t
        before[c] = (t, ps)
    # apply
    for c in chunks:
        t, ps = before[c]
        for (cc, n, kind, old, new, why) in [e for e in E if e[0] == c]:
            i = n - 1
            cnt = ps[i].count(old)
            if cnt != 1:
                raise SystemExit("HIT %d %s#%d old=%r" % (cnt, c, n, old[:40]))
            ps[i] = ps[i].replace(old, new)
        newt = "\n\n".join(ps)
        if not dry:
            L.backup(c)
            L.wr(os.path.join(L.OUTDIR, c + ".txt"), newt)
    # verify
    stats = {}
    for c in chunks:
        t = L.rd(os.path.join(L.OUTDIR, c + ".txt"))
        ps = t.split("\n\n")
        assert (len(ps), t.count("\n")) == SHAPE[c], ("AFTER", c, len(ps), t.count("\n"))
        assert "\r" not in t, ("CR", c)
        stats[c] = (len(ps), t.count("\n"))
    # diff report
    out = []
    for (c, n, kind, old, new, why) in E:
        out.append("[%s#%d %s]\n- %s\n+ %s\n  ※%s" % (c, n, kind, old, new, why))
    if not dry:
        with io.open(os.path.join(HERE, "_z8_1857_diff.txt"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n\n".join(out) + "\n")
        with io.open(LOG, "w", encoding="utf-8") as f:
            f.write(json.dumps({"n": 1857, "edits": len(E),
                                "segs": len(set((e[0], e[1]) for e in E)),
                                "yi": sum(1 for e in E if e[2] == "義"),
                                "run": sum(1 for e in E if e[2] == "潤"),
                                "veto": 3, "doubt": 1,
                                "shape": stats}, ensure_ascii=False) + "\n")
    print("edits=%d segs=%d yi=%d run=%d" % (
        len(E), len(set((e[0], e[1]) for e in E)),
        sum(1 for e in E if e[2] == "義"), sum(1 for e in E if e[2] == "潤")))
    print("shape", stats)


if __name__ == "__main__":
    main(dry="--dry" in sys.argv)
