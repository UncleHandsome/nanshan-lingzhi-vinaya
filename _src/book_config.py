# 出處書名／路徑 → 書別（長名先判，避免《…行事鈔資持記》被判成行事鈔）
_BOOK_MARKS = (
    ('資持記', '資持記'), ('資持', '資持記'),
    ('比丘尼鈔', '尼鈔'), ('尼鈔', '尼鈔'),
    ('拾毗尼', '義鈔'), ('義鈔', '義鈔'),
    ('含注戒本疏', '戒疏'), ('行宗記', '戒疏'), ('戒疏', '戒疏'),
    ('羯磨疏', '業疏'), ('濟緣記', '業疏'), ('業疏', '業疏'),
    ('行事鈔', '行事鈔'), ('刪繁補闕', '行事鈔'),
)


def _book_from_name(name):
    for mark, book in _BOOK_MARKS:
        if mark in name:
            return book
    return ''


def book_of(path_or_text):
    """由「（出處：《…》）」優先判斷書別，取不到才查路徑。"""
    p = str(path_or_text or '')
    m = re.search(r'（出處[：:]\s*《([^》]+)》', p) or re.search(r'出處[：:]\s*《([^》]+)》', p)
    if m:
        b = _book_from_name(m.group(1))
        if b:
            return b
    b = _book_from_name(p)
    return b or '業疏'


def cfg(book):
    return CFG.get(book, CFG['業疏'])


def fmt_for(book, units=None):
    """依實際 units 的標籤決定輸出格式（單邊段只印該標籤）。"""
    labs = [u.get('lab') for u in (units or []) if u.get('lab')]
    if not labs:
        return cfg(book)['fmt']
    seen = []
    for lab in labs:
        if lab not in seen:
            seen.append(lab)
    if len(seen) == 1:
        return '【%s】……' % seen[0]
    return '\n'.join('【%s】……' % lab for lab in seen)


def note_for(book, labs=None):
    """依書別與實際欄位回傳精準 note（單欄疏／記、純律註序、雙欄）。"""
    labs = set(labs or [])
    if book in ('業疏', '戒疏'):
        if labs and not (labs & {'疏文', '記文'}):
            return '%s單欄原文' % book
        base = SHUJI_NOTE_YS if book == '業疏' else SHUJI_NOTE_JX
        if not ({'疏文', '記文'} <= labs):
            return base + '單欄段依本欄脈絡審斷，勿搬他欄專論。'
        return base
    return cfg(book).get('note', '') or book
