def variants(old):
    vs = [old]
    if "「" in old or "」" in old:
        vs.append(old.replace("「", "『").replace("」", "』"))
        vs.append(old.replace("『", "「").replace("』", "」"))
    if old.endswith("。"):
        vs.append(old[:-1])
    return vs

ALT = re.compile(r"（或[：]?[^（）]*）")

def clean_new(new):
    # drop inline editorial alternatives like （或：...）
    return ALT.sub("", new)

# edits applied to every occurrence (count > 1 expected)
