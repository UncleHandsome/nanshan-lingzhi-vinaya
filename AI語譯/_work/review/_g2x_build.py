order = []          # first-occurrence key order
cur = {}            # key -> text
origin = {}         # key -> report index (first)
problems = []

for i, d in enumerate(ROWS, 1):
    key = (d["book"], d["chunk"], d["seg"])
    if i in SKIPPED:
        continue
    text = cur.get(key, d["current"])
    if key not in cur:
        order.append(key)
        origin[key] = i
    for old, new in OPS[i]:
        if old == "__SET__":
            text = new
            continue
        n = text.count(old)
        if n != 1:
            problems.append(f"row {i} ({d['gid']}): match count {n} for old={old[:40]!r}")
            continue
        text = text.replace(old, new)
    cur[key] = text

if problems:
    print("PROBLEMS:")
    for p in problems:
        print(" -", p)

