for k, v in segs.items():
    cur = v["cur"]
    seen = set()
    for x in v["rows"]:
        key = (x["gid"], x["seg"], x["cls"])
        if key in SKIP:
            continue
        if key in MANUAL:
            edits = MANUAL[key]
        else:
            edits = x["pairs"]
        if not edits:
            continue
        for old, new in edits:
            if not old or not new:
                continue
            if (old, new) in seen:
                continue
            seen.add((old, new))
            new = clean_new(new)
            hit = find(old, cur)
            if hit is None:
                problems.append((x["gid"], k[0], k[1], old[:40], "NOTFOUND"))
                continue
            if (x["gid"], x["seg"], x["cls"]) in GLOBAL:
                cur = cur.replace(hit, new)
                applied += 1
                continue
            if new in cur and new != hit:
                problems.append((x["gid"], k[0], k[1], old[:40], "NEW_EXISTS"))
                continue
            pos = cur.find(hit)
            new_eff = new
            if new_eff.endswith("。") and cur[pos + len(hit):pos + len(hit) + 1] == "。":
                new_eff = new_eff[:-1]
            cur = cur[:pos] + new_eff + cur[pos + len(hit):]
            applied += 1
    v["new"] = cur

def norm_quote(s):
    return s.replace("『", "「").replace("』", "」").replace(" ", "")

