errs = []
order = []
groups = {}   # (chunk, seg) -> {"base":..., "rows":[i], "text":...}
skipped = []

for r in rows:
    i = r["i"]
    key = (r["chunk"], r["seg"])
    if not OPS.get(i):
        skipped.append(i)
        continue
    if key not in groups:
        groups[key] = {"base": r["current"], "rows": [], "text": r["current"], "chunk": r["chunk"], "seg": r["seg"]}
        order.append(key)
    else:
        if groups[key]["base"] != r["current"]:
            errs.append("row %02d: duplicate seg with different base text" % i)
    groups[key]["rows"].append(i)

for key in order:
    g = groups[key]
    done = set()
    for i in g["rows"]:
        for old, rep, cnt in OPS[i]:
            if (old, rep) in done:
                continue
            c = g["text"].count(old)
            if c != cnt:
                errs.append("row %02d %s seg %s: expected %d of %r, found %d" % (i, key[0], key[1], cnt, old, c))
                continue
            g["text"] = g["text"].replace(old, rep)
            done.add((old, rep))

if errs:
    print("ERRORS:")
    for e in errs:
        print(" ", e)
    raise SystemExit(1)

outs = []
for key in order:
    g = groups[key]
    t = g["text"]
    assert "\t" not in t and "\n" not in t and "\r" not in t, key
    assert t == t.strip(), key
    assert t != g["base"], ("no change", key)
    outs.append(("03_業疏", g["chunk"], g["seg"], t, g["rows"]))

print("out rows", len(outs), "skipped", skipped)

with io.open("AI語譯/_work/review/fix_r8_g1.tsv", "w", encoding="utf-8", newline="\n") as f:
    for b, c, s, t, _ in outs:
        f.write("%s\t%s\t%s\t%s\n" % (b, c, s, t))
print("written")
