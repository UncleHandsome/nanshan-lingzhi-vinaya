src = json.load(open(SRC, encoding="utf-8"))["items"]
assert len(src) == len(texts), (len(src), len(texts))

PUNC = "，。、；：？！「」"
out = []
problems = []
for i, (it, t) in enumerate(zip(src, texts)):
    orig = it["text"]
    stripped = "".join(c for c in t if c not in PUNC)
    stripped_o = "".join(c for c in orig if c not in PUNC)
    if stripped != stripped_o:
        # locate first difference
        j = 0
        while j < min(len(stripped), len(stripped_o)) and stripped[j] == stripped_o[j]:
            j += 1
        problems.append((i, j, stripped_o[max(0, j-8):j+8], stripped[max(0, j-8):j+8], len(stripped_o), len(stripped)))
    if not (t.endswith("。") or t.endswith("。」") or t.endswith('。"')):
        problems.append((i, "no-final-period", t[-6:], "", 0, 0))
    out.append({"file": it["file"], "line": it["line"], "text": t})

if problems:
    for p in problems:
        print("PROBLEM", p)
    raise SystemExit("verification failed")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
    f.write("\n")
