errors = []
rows_out = []
for r in recs:
    i = r["idx"]
    if i in skip:
        continue
    cur = r["current"]
    if i in MAN:
        spec = MAN[i]
        if spec[0] == "FULL":
            new = spec[1]
        else:
            new = cur
            for old, rep in spec:
                if old == "END":
                    new = new + rep
                elif old == "START":
                    new = rep + new
                else:
                    if new.count(old) != 1:
                        errors.append((i, "count", new.count(old), old))
                    new = new.replace(old, rep, 1)
    elif r["mode"] == "auto":
        new = r["new"]
        if i in B_REWRITE:
            # rebuild from current with the cleaned replacement
            new = cur
            for p in sorted(r["ops"], key=lambda x: -x["pos"]):
                b = B_REWRITE[i] if i in B_REWRITE else p["b"]
                new = new[:p["pos"]] + b + new[p["pos"]+len(p["am"]):]
    else:
        errors.append((i, "unhandled", r["mode"], ""))
        continue
    new = new.rstrip("\n")
    if "\n" in new or "\t" in new:
        errors.append((i, "internal_newline", "", ""))
    rows_out.append((i, r["book"], r["chunk"], r["seg"], new))

print("errors:", errors)
print("rows_out:", len(rows_out), "skipped:", len(skip))

# validations
bad = []
for i, book, chunk, seg, new in rows_out:
    if "\n" in new or "\t" in new:
        bad.append((i, "newline/tab"))
    if not new.strip():
        bad.append((i, "empty"))
print("bad:", bad)

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    for i, book, chunk, seg, new in rows_out:
        f.write(f"{book}\t{chunk}\t{seg}\t{new}\n")

