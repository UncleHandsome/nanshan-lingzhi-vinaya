errs = []
outs = []
for i, x in enumerate(res, 1):
    if i not in EDITS:
        continue
    cur = x['out_para']
    new = cur
    for old, rep in EDITS[i]:
        c = new.count(old)
        if c != 1:
            errs.append('row %d: count=%d for [%s]' % (i, c, old[:40]))
            continue
        new = new.replace(old, rep)
    if '\t' in new or '\n' in new:
        errs.append('row %d: contains tab/newline' % i)
    if new == cur:
        errs.append('row %d: unchanged' % i)
    outs.append((i, x['chunk'], x['seg'], new))

if errs:
    print('ERRORS:')
    for e in errs:
        print(' ', e)
    sys.exit(1)

p = os.path.join(REV, 'fix_loc_g1.tsv')
with io.open(p, 'w', encoding='utf-8', newline='\n') as w:
    for i, chunk, seg, new in outs:
        w.write('02_戒疏\t%s\t%s\t%s\n' % (chunk, seg, new))
print('wrote %d rows -> %s' % (len(outs), p))

