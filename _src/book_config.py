def note_for(book, labs=None):
    """依書別與實際欄位回傳精準 note（單欄疏／記、純律註序、雙欄）。"""
    labs = set(labs or [])
    if book in ('業疏', '戒疏'):
        if labs and not (labs & {'疏文', '記文'}):
            return '%s單欄原文' % book
        base = SHUJI_NOTE_YS if book == '業疏' else SHUJI_NOTE_JX
        if not ({'疏文', '記文'} <= labs):
            return base + '單欄段依本欄脈絡審斷，勿搬他欄專論。'
        return base
    return cfg(book).get('note', '') or book

def book_of(path_or_text):
    """由批次路徑判斷書別。"""
    p = str(path_or_text)
    if '比丘尼鈔' in p or '尼鈔' in p:
        return '尼鈔'
    if '資持記' in p or '資持' in p:
        return '資持記'
    if '行事鈔' in p:
        return '行事鈔'
    if '拾毗尼' in p or '義鈔' in p:
        return '義鈔'
    if '戒疏' in p:
        return '戒疏'
    return '業疏'


def cfg(book):
    return CFG.get(book, CFG['業疏'])


def fmt_for(book, units=None):
    """依實際 units 的標籤決定輸出格式（單邊段只印該標籤）。"""
    labs = [u.get('lab') for u in (units or []) if u.get('lab')]
    if not labs:
        return cfg(book)['fmt']
    seen = []
    for lab in labs:
        if lab not in seen:
            seen.append(lab)
    if len(seen) == 1:
        return '【%s】……' % seen[0]
    return '\n'.join('【%s】……' % lab for lab in seen)
