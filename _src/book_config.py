# 已知序跋撰者與年代（僅兩篇卷首序，屬資料事實而非抽樣詞例）
PREFACE_ERA = {
    ('業疏', '01a_0001'): '宋・元照《濟緣記序》',
    ('戒疏', '00_卷首_0011'): '日本江戶安永二年會本序',
}


def preface_era(book, key=''):
    """序跋出處提示：已知者寫明撰者年代，其餘給判斷依據。"""
    k = str(key or '')
    if (book, k) in PREFACE_ERA:
        return PREFACE_ERA[(book, k)]
    if '卷首' in k or k.startswith('00_'):
        return '卷首序跋（撰者與年代須依題署、書名與史傳判斷）'
    return '序跋／駢文（撰者與年代須依題署、書名與史傳判斷）'


def _has_preface(book, labs, src, key=''):
    """只認明確序跋訊號：序文標籤、卷首 key、卷首體裁開頭或序跋標籤。"""
    if '序文' in set(labs or []):
        return True
    k = str(key or '')
    if '卷首' in k or k.startswith('00_'):
        return True
    head = (src or '')[:80]
    if re.match(r'^\s*(?:序|敘|叙|原夫|蓋聞|竊以|謹序|題辭)', head):
        return True
    return bool(re.match(r'^\s*【(?:疏序|記序|會本序|序文)】', head))


def _has_dangling(src, out):
    for t in (out, src):
        s = re.sub(r'[\s）」』】]+$', '', t or '')
        if DANGLING_RE.search(s):
            return True
    return False


DANGLING_RE = re.compile(r'(?:云|曰|說|白)[。：:]\s*$|等[。：:]\s*$|：\s*$')


def notes_for(book, labs=None, src='', out='', long=False, key='', typo=False):
    """依書別、段別與風險訊號回傳動態 note 字典（未命中者為空字串）。

    typo=True 由 recheck_scan 的 TYPO/形訛旗標傳入；不再用寫死的抽樣訛字表。
    """
    labs = list(dict.fromkeys(labs or []))
    labset = set(labs)
    dual = bool(book in ('業疏', '戒疏') and {'疏文', '記文'} <= labset)
    era = preface_era(book, key) if _has_preface(book, labs, src, key) else ''
    typo = bool(typo or '〔' in (src or ''))
    return {
        'book_note': note_for(book, labs),
        'dual_note': DUAL_NOTE if dual else '',
        'long_note': LONG_NOTE if long else '',
        'preface_note': PREFACE_NOTE.replace('{pref_era}', era) if era else '',
        'dangling_note': DANGLING_NOTE if _has_dangling(src, out) else '',
        'typo_note': TYPO_NOTE if typo else '',
        'pref_era': era,
    }


