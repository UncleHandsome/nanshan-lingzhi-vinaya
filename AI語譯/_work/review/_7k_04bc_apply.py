def main(dry=True):
    with io.open(OUT, "r", encoding="utf-8", newline="") as f:
        raw = f.read()
    eol = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.split(eol)
    changed = 0
    for idx in sorted(EDITS):
        old = lines[idx - 1]
        cur = old
        for find, new in EDITS[idx]:
            c = cur.count(find)
            if c != 1:
                raise SystemExit("FIND 不唯一/不存在 line#%d count=%d %r" % (idx, c, find[:30]))
            cur = cur.replace(find, new)
        if cur == old:
            raise SystemExit("無變化 line#%d" % idx)
        print("line#%d  %d→%d 字  ops=%d" % (idx, len(old), len(cur), len(EDITS[idx])))
        lines[idx - 1] = cur
        changed += 1
    if dry:
        print("DRY: %d 段待改" % changed)
        return
    with io.open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(eol.join(lines))
    print("寫入 %s：%d 段" % (OUT, changed))


if __name__ == "__main__":
    main(dry=(len(sys.argv) > 1 and sys.argv[1] == "dry"))
