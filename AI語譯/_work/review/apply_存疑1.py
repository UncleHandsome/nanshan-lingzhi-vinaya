def readfile(p):
    raw = open(p, encoding="utf-8", newline="").read()
    eol = "\r\n" if "\r\n" in raw else "\n"
    return raw, eol, raw.replace("\r\n", "\n")

def main():
    apply = "--apply" in sys.argv
    files = collections.OrderedDict()
    for book, chunk, seg, old, new, tid in EDITS:
        files.setdefault((book, chunk), []).append((seg, old, new, tid))
    stat = collections.Counter()
    notes = []
    for (book, chunk), items in files.items():
        p = f"AI語譯/out/{book}/{chunk}.txt"
        raw, eol, text = readfile(p)
        blocks = text.split("\n\n")
        changed = False
        for seg, old, new, tid in items:
            b = blocks[seg-1]
            if old and old not in b:
                stat["already"] += 1
                continue
            if not old:
                if new and new in b:
                    stat["already"] += 1
                else:
                    stat["conflict"] += 1
                    notes.append(f"CONFLICT {tid} {book}/{chunk}#{seg} (insert)")
                continue
            n = b.count(old)
            if n != 1:
                stat["conflict"] += 1
                notes.append(f"CONFLICT {tid} {book}/{chunk}#{seg} count={n}")
                continue
            blocks[seg-1] = b.replace(old, new, 1)
            stat["applied"] += 1
            changed = True
        if changed and apply:
            out = "\n\n".join(blocks)
            if eol == "\r\n":
                out = out.replace("\n", "\r\n")
            open(p, "w", encoding="utf-8", newline="").write(out)
            stat["files"] += 1
    print(f'applied={stat["applied"]} already={stat["already"]} conflict={stat["conflict"]} files={stat["files"]} (apply={apply})')
    for n in notes:
        print(n)

if __name__ == "__main__":
    main()
