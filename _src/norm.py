# -*- coding: utf-8 -*-
"""定稿確定性正規化（不花 token）。"""
import re

VAR_MAP = str.maketrans('煑竪虗汙竝説爲着衆盋鉢艸壍众问这为应经说义体归无时数却徧牀厨裏羣纔呪婬眞敎菓', '煮豎虛污並說為著眾缽缽草塹眾問這為應經說義體歸無時數卻遍床廚裡群才咒淫真教果')
URL_RE = re.compile(r'https?://[^\s）)」』】]+')
TAG_RE = re.compile(r'^\s*【(?:疏文|記文|鈔文|律文|註文|序文)】\s*$')


KNOWN_BOOKS = ('四分律', '五分律', '十誦律', '摩訶僧祇律', '善見律毘婆沙',
               '隨機羯磨', '行事鈔', '資持記', '業疏', '戒疏', '尼鈔', '義鈔',
               '濟緣記', '行宗記', '成實論', '優婆塞戒經', '大般涅槃經', '梵網經', '律二十二明了論',
               '薩婆多毘尼毘婆沙', '薩婆多部毘尼摩得勒伽', '四分比丘尼戒本',
               '大比丘三千威儀', '關中創立戒壇圖經', '中阿含經', '長阿含經',
               '瑜伽師地論', '雜阿毘曇心論', '增壹阿含經', '含注戒本', '四分僧戒本', '僧羯磨', '尼羯磨',
               '業疏科', '戒疏科', '行事鈔科', '義鈔科', '尼鈔科',
               '南山律學辭典', '五分律', '十誦律')


def _book_title(m):
    body = m.group(1)
    follow = m.group(2) or ''
    if body in KNOWN_BOOKS:
        return '《' + body + '》' + follow
    return '〈' + body + '〉' + follow


def _tag_newline(m):
    return m.group(1) + chr(10)


LABEL_FIX = {'【修訂譯文】': None, '【修正後譯文】': None,
             '【鈔文（修訂）】': '【鈔文】', '【記文（修訂）】': '【記文】',
             '【疏文（修訂）】': '【疏文】', '【律文（修訂）】': '【律文】',
             '【註文（修訂）】': '【註文】', '【序文（修訂）】': '【序文】'}


def _strip_md(s):
    s = re.sub(r"(?m)^\s*#{1,6}\s+", "", s)
    s = s.replace(chr(42)*2, "")
    s = s.replace('`', '')
    s = re.sub(r'(?m)^\s*[-*]\s+', '', s)
    s = re.sub(r'\[[^\]]*\]\(\)', '', s)
    return s


def normalize(text):
    _lab = '鈔文'
    for _cand in ('疏文', '記文', '律文', '註文', '序文'):
        if '【%s】' % _cand in text or '【%s（修訂）】' % _cand in text:
            _lab = _cand
            break
    lines = []
    for ln in text.split('\n'):
        _depth = 0
        s = ln.rstrip()
        s = URL_RE.sub('', s)
        s = _strip_md(s)
        _parts = re.split(r'([「」『』])', s)
        for _i in range(len(_parts)):
            if _parts[_i] in ('「', '『'):
                _depth += 1
            elif _parts[_i] in ('」', '』'):
                _depth = max(0, _depth - 1)
            elif _depth == 0:
                _parts[_i] = _parts[_i].translate(VAR_MAP)
        s = ''.join(_parts)
        s = re.sub(r'〈([^〈〉《》]{1,20})〉(篇|品|章|節|門|科|犍度|境|體|軌)?', _book_title, s)
        s = re.sub(r'《([^《》〈〉]{1,12}(?:篇|品|章|節|門|犍度))》', r'〈\1〉', s)
        s = re.sub(r'^(?:提问|提問|問曰|问曰)\s*：', '問：', s, flags=re.M)
        s = re.sub(r'^(?:回答|答曰|答云|答言)\s*：', '答：', s, flags=re.M)
        for a, b in (('精准', '精準'), ('通达', '通達'), ('没有', '沒有'),
                     ('时候', '時候'), ('这个', '這個'), ('那个', '那個'),
                     ('我们', '我們'), ('他们', '他們'), ('什么', '什麼'),
                     ('因为', '因為'), ('所以', '所以'), ('已经', '已經'),
                     ('现在', '現在'), ('实际', '實際'), ('种种', '種種'),
                     ('这样', '這樣'), ('那样', '那樣'), ('动作', '動作'),
                     ('学习', '學習'), ('觉得', '覺得'), ('看见', '看見'),
                     ('观察', '觀察'), ('认识', '認識'), ('讨论', '討論'),
                     ('证明', '證明'), ('过来', '過來'), ('还是', '還是'),
                     ('对于', '對於'), ('发现', '發現'), ('个人', '個人'),
                     ('我们', '我們'), ('么', '麼'), ('颗', '顆'), ('达', '達'), ('没', '沒'), ('过', '過'),
                     ('与', '與'), ('现', '現'), ('实', '實'), ('际', '際'),
                     ('种', '種'), ('样', '樣'), ('动', '動'), ('学', '學'),
                     ('觉', '覺'), ('见', '見'), ('观', '觀'), ('识', '識'),
                     ('论', '論'), ('证', '證'), ('个', '個'), ('们', '們'), ('这', '這'), ('那', '那'), ('还', '還'), ('发', '發'), ('对', '對'), ('从', '從'), ('来', '來')):
            s = s.replace(a, b)
        for _a, _target in LABEL_FIX.items():
            if _a in s:
                s = s.replace(_a, _target or ('【%s】' % _lab))
        s = re.sub(r'\s+$', '', s)
        s = re.sub(r'^(【(?:疏文|記文|鈔文|律文|註文|序文)】)\s*(?=\S)', _tag_newline, s)
        lines.append(s)
    out = '\n'.join(lines)
    out = re.sub(r'\n{3,}', '\n\n', out)
    return out.strip() + '\n'
