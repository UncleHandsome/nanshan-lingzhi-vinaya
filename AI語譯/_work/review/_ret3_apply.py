def run(apply=False):
    ok = True
    by_chunk = {}
    for e in EDITS:
        by_chunk.setdefault(e["chunk"], []).append(e)
    bak = os.path.join(L.ROOT, "歸檔", "ret3套用_04比丘尼鈔_修正前")
    if apply:
        os.makedirs(bak, exist_ok=True)
    stats = []
    for chunk, es in sorted(by_chunk.items()):
        p, t = L.load(chunk)
        ps = L.paras(t)
        n_before = len(ps)
        for e in es:
            i = e["para"] - 1
            if i < 0 or i >= len(ps):
                print("FAIL range", chunk, e["para"]); ok = False; continue
            c = ps[i].count(e["old"])
            if c != 1:
                print("FAIL count=%d" % c, chunk, e["para"], e["eid"], "|", e["old"][:60])
                ok = False
                continue
            ps[i] = ps[i].replace(e["old"], e["new"], 1)
            print("OK", chunk, e["para"], e["eid"])
        if not ok:
            continue
        nt = "\n\n".join(ps)
        if len(L.paras(nt)) != n_before:
            print("FAIL para count changed", chunk); ok = False; continue
        stats.append((chunk, os.path.basename(p), n_before, t.count("\n"), nt.count("\n"),
                      t.count("\r"), nt.count("\r"), os.path.getsize(p), len(nt.encode())))
        if apply:
            dst = os.path.join(bak, os.path.basename(p))
            if not os.path.exists(dst):
                shutil.copy2(p, dst)
            with open(p, "w", encoding="utf-8", newline="") as f:
                f.write(nt)
    print("\n== summary ==")
    for s in stats:
        print("%-6s %-22s paras=%d lines %d->%d CR %d->%d bytes %d->%d" % s)
    print("edits:", len(EDITS), "chunks:", len(by_chunk), "all_ok:", ok)
    return ok


if __name__ == "__main__":
    run(apply="--apply" in sys.argv)
