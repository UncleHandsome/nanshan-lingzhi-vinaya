out, bad = [], 0
for n, marks, tg in S:
    t = JI[n]['text']
    assert t.count('') == len(t) + 1
    # 1) 以短詞確定切點位置
    cuts, pos = [], 0
    for short, long in marks:
        i = t.find(short, pos)
        if i <= 0:
            print('!! n=%d 短詞找不到或不為首段: %r i=%d' % (n, short, i)); bad += 1; break
        if t.count(short) != 1:
            print('!! n=%d 短詞重複%d次: %r' % (n, t.count(short), short)); bad += 1; break
        cuts.append(i); pos = i
    else:
        # 2) 長 marker 必須同位置、逐字出現、唯一
        for (short, long), i in zip(marks, cuts):
            if not t.startswith(long, i):
                print('!! n=%d marker 與切點不符: %r @%d' % (n, long, i)); bad += 1; break
            if t.count(long) != 1:
                print('!! n=%d marker 重複%d次: %r' % (n, t.count(long), long)); bad += 1; break
        else:
            segs = [t[a:b] for a, b in zip([0] + cuts, cuts + [len(t)])]
            if len(segs) != len(tg) or tg != sorted(tg) or len(set(tg)) != len(tg) or not all(s.strip() for s in segs):
                print('!! n=%d 段落/目標不符: %s' % (n, tg)); bad += 1; continue
            if any(not (1 <= x <= NC) for x in tg):
                print('!! n=%d 目標越界' % n); bad += 1; continue
            out.append({'n': n, 'markers': [m[1] for m in marks], 'targets': tg})

print('total', len(out), 'bad', bad)
