with open(SRC, "r", encoding="utf-8", newline="") as f:
    rows = list(csv.reader(f, delimiter="\t"))

header, body = rows[0], rows[1:]
out_rows = []
used = set()
problems = []

for r in body:
    if len(r) < 11:
        continue
    book, chunk, seg, level, cls, status, problem, sugg, orig, tr, cur = r[:11]
    if chunk not in TARGETS:
        continue
    if not cur.strip():
        continue
    key = (chunk, seg)
    if key not in FIXES:
        problems.append("NO_FIX " + chunk + " seg " + seg)
        continue
    new = cur
    for old, rep in FIXES[key]:
        c = new.count(old)
        if c != 1:
            problems.append("ANCHOR %s seg %s count=%d :: %s" % (chunk, seg, c, old[:40]))
            new = None
            break
        new = new.replace(old, rep)
    if new is None:
        continue
    used.add(key)
    if "\t" in new or "\n" in new or "\r" in new:
        problems.append("BADCHAR " + chunk + " seg " + seg)
    out_rows.append((book, chunk, seg, new))
    ratio = len(new) / len(cur) if cur else 0
    print("OK %-9s seg %-4s cur=%3d new=%3d ratio=%.2f" % (chunk, seg, len(cur), len(new), ratio))

for key in FIXES:
    if key not in used:
        problems.append("UNUSED FIX " + key[0] + " seg " + key[1])

print("-" * 60)
print("rows written:", len(out_rows))
if problems:
    print("PROBLEMS:")
    for p in problems:
        print("  ", p)
    sys.exit(1)

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    for book, chunk, seg, new in out_rows:
        f.write("%s\t%s\t%s\t%s\n" % (book, chunk, seg, new))
print("wrote", OUT)
