extra_ops = [k for k in OPS if k not in {g['key'] for g in groups}]
print('ops without group:', extra_ops)

def variants(s):
    yield s
    # quote-style variant
    if '『' in s or '』' in s:
        yield s.replace('『', '「').replace('』', '」')
    if '「' in s or '」' in s:
        yield s.replace('「', '『').replace('」', '』')

out_lines = []
log = []
applied_rows = 0
skipped_rows = 0
for g in groups:
    chunk, seg = g['key']
    cur = g['current']
    nr = len(g['rows'])
    if g['key'] in SKIP_KEYS:
        skipped_rows += nr
        log.append(('SKIP-APPLIED-ALL', chunk, seg, nr))
        continue
    edits = OPS[g['key']]
    text = cur
    hits = 0
    misses = []
    for old, new in edits:
        done = False
        for ov in variants(old):
            cnt = text.count(ov)
            if cnt == 1:
                text = text.replace(ov, new)
                hits += 1
                done = True
                break
            if cnt > 1:
                raise SystemExit('AMBIGUOUS %s %s %r -> %d' % (chunk, seg, ov[:30], cnt))
        if not done:
            misses.append(old[:40])
    if hits == 0:
        skipped_rows += nr
        log.append(('SKIP-APPLIED', chunk, seg, nr, misses))
        continue
    if misses:
        log.append(('PARTIAL-MISS', chunk, seg, misses))
    out_lines.append((chunk, seg, text))
    skipn = EXTRA_SKIP_ROWS.get(g['key'], 0)
    applied_rows += nr - skipn
    skipped_rows += skipn

for a, b, t in out_lines:
    assert '\t' not in t and '\n' not in t and '\r' not in t
keys = [(a, b) for a, b, _ in out_lines]
assert len(keys) == len(set(keys)), 'duplicate keys'

with io.open(BASE + r'/fix_re7_g2.tsv', 'w', encoding='utf-8', newline='') as f:
    for chunk, seg, text in out_lines:
        f.write('03_業疏\t%s\t%s\t%s\n' % (chunk, seg, text))

for e in log:
    print(e)
print('---')
print('output lines:', len(out_lines))
print('applied rows:', applied_rows, 'skipped rows:', skipped_rows, 'total:', applied_rows + skipped_rows)
