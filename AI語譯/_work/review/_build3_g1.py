def ops_for(d):
    ln = d["_line"]
    if ln in M:
        return ("SKIP", []) if M[ln] == SKIP else ("OPS", list(M[ln]))
    sug = d["suggestion"].strip()
    if not sug:
        return ("EMPTY", [])
    ops = parse_ops(sug)
    if not ops:
        return ("NOPAT", [])
    return ("AUTO", ops)

def norm(s):
    return s.replace("『", "「").replace("』", "」")

def main():
    rows = load()
    groups = OrderedDict()
    for d in rows:
        groups.setdefault((d["book"], d["chunk"], d["seg"]), []).append(d)
    out = []
    stats = []
    for key, grp in groups.items():
        base = grp[0]["current"]
        cur = base
        per = []
        for d in grp:
            kind, ops = ops_for(d)
            applied, miss = 0, []
            for a, b in ops:
                done = False
                for aa in (a, norm(a)):
                    if aa in cur:
                        cur = cur.replace(aa, b, 1)
                        applied += 1; done = True; break
                if not done:
                    miss.append(a)
            per.append({"line": d["_line"], "gid": d["gid"], "kind": kind,
                        "applied": applied, "miss": miss})
        txt = cur.rstrip("\n")
        txt = txt.replace("\n", "")
        out.append((key, txt, base, per))
        stats.extend(per)
    return out, stats

