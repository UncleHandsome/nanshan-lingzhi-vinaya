def render(tmpl, **vals):
    """填提示詞佔位符；未給的已知佔位符一律填空（避免死碼上線）。"""
    vals.setdefault('substantive_style', SUBSTANTIVE_STYLE)
    vals.setdefault('logic_checklist', LOGIC_CHECKLIST)
    vals.setdefault('cite_style', CITE_STYLE_MIN)
    s = tmpl
    for k in PLACEHOLDERS:
        s = s.replace('{%s}' % k, str(vals.get(k) or ''))
    return s


