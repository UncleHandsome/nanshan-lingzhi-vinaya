def load(chunk):
    p = os.path.join(OUT, chunk + ".txt")
    b = open(p, "rb").read()
    return p, b, b.decode("utf-8")


def para_lines(text):
    lines = text.split("\n")
    idx = [i for i, ln in enumerate(lines) if ln.rstrip("\r").strip()]
    return lines, idx


def do_check():
    bad = 0
    bych = {}
    for chunk, seg, pairs in EDITS:
        bych.setdefault(chunk, []).append(seg)
    for chunk in bych:
        p, b, t = load(chunk)
        lines, idx = para_lines(t)
        print("== %s  bytes=%d paras=%d crlf=%d lf=%d" %
              (chunk, len(b), len(idx), t.count("\r\n"), len(re.findall(r"(?<!\r)\n", t))))
        for chunk2, seg, pairs in EDITS:
            if chunk2 != chunk:
                continue
            if seg > len(idx):
                print("  !! seg %d out of range" % seg); bad += 1; continue
            body = lines[idx[seg - 1]].rstrip("\r")
            for old, new in pairs:
                c = body.count(old)
                if c != 1:
                    print("  !! seg %d count=%d for: %s" % (seg, c, old[:40])); bad += 1
                print("  seg %-3d ok=%s  %s -> %s" % (seg, c == 1, old[:28], new[:28]))
    print("BAD =", bad)
    return bad


def do_apply():
    # 先全量檢查
    if do_check() != 0:
        print("檢查未過，未套用"); return 1
    bych = {}
    for chunk, seg, pairs in EDITS:
        bych.setdefault(chunk, []).append((seg, pairs))
    for chunk, items in bych.items():
        p, b, t = load(chunk)
        os.makedirs(BAK, exist_ok=True)
        bp = os.path.join(BAK, chunk + "_a.txt")
        if not os.path.exists(bp):
            shutil.copy2(p, bp)
            print("backup", bp)
        lines, idx = para_lines(t)
        before = len(idx)
        crlf0 = t.count("\r\n")
        touched = []
        for seg, pairs in items:
            i = idx[seg - 1]
            raw = lines[i]
            eol = "\r" if raw.endswith("\r") else ""
            body = raw[:-1] if eol else raw
            for old, new in pairs:
                assert body.count(old) == 1, (chunk, seg, old)
                body = body.replace(old, new)
            lines[i] = body + eol
            touched.append(seg)
        out = "\n".join(lines)
        assert out.count("\r\n") == crlf0, "line ending changed"
        _, _, t2 = None, None, out
        lines2, idx2 = para_lines(t2)
        assert len(idx2) == before, "para count changed"
        io.open(p, "w", encoding="utf-8", newline="").write(out)
        print("applied", chunk, sorted(touched), "paras", before, "->", len(idx2), "crlf", crlf0)
    return 0


def do_verify():
    bych = {}
    for chunk, seg, pairs in EDITS:
        bych.setdefault(chunk, []).append(seg)
    for chunk, segs in bych.items():
        p, b, t = load(chunk)
        bp = os.path.join(BAK, chunk + "_a.txt")
        ok = os.path.exists(bp)
        old = io.open(bp, encoding="utf-8", newline="").read() if ok else None
        lines, idx = para_lines(t)
        olines, oidx = para_lines(old) if ok else ([], [])
        diff = [i + 1 for i, (a, c) in enumerate(zip(olines, lines)) if a != c] if ok else []
        # 以非空段落序號比對
        oseq = [x for x in olines if x.strip()]
        nseq = [x for x in lines if x.strip()]
        dseg = [i + 1 for i, (a, c) in enumerate(zip(oseq, nseq)) if a != c]
        print("== %s paras %d->%d crlf %d->%d bytes %d->%d  changed_segs=%s  expect=%s  %s" % (
            chunk, len(oidx), len(idx), old.count("\r\n") if ok else -1, t.count("\r\n"),
            len(old.encode("utf-8")) if ok else -1, len(b),
            dseg, sorted(segs), "OK" if dseg == sorted(segs) else "MISMATCH"))
    return 0


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if mode == "--check":
        sys.exit(1 if do_check() else 0)
    elif mode == "--apply":
        sys.exit(do_apply())
    elif mode == "--verify":
        sys.exit(do_verify())
