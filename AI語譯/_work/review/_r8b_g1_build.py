# group rows by segment key, preserving report order
groups = {}
order = []
for i, r in enumerate(rows):
    key = (r["book"], r["chunk"], r["seg"])
    if i in OPS:
        if key not in groups:
            groups[key] = {"base": r["current"], "edits": [], "rows": []}
            order.append(key)
        groups[key]["edits"].append((i, OPS[i]))
        groups[key]["rows"].append(i)

problems = []
out_lines = []
report = io.open(os.path.join(base, "_r8b_g1_diff.txt"), "w", encoding="utf-8")
for key in order:
    g = groups[key]
    text = g["base"]
    report.write("=== %s | %s | seg %s | rows %s\n" % (key[0], key[1], key[2], g["rows"]))
    for i, edits in g["edits"]:
        for old, new in edits:
            n = text.count(old)
            if n != 1:
                problems.append("row %d: old occurs %d times: %s" % (i, n, old[:30]))
                continue
            j = text.find(old)
            before = text[max(0, j - 35):j]
            after = text[j + len(old):j + len(old) + 35]
            text = text.replace(old, new, 1)
            report.write("  [%d] ...%s >>> %s >>> %s...\n" % (i, before, new, after))
    text = text.replace("\n", "")
    if "\t" in text:
        problems.append("%s: tab in new" % (key,))
    out_lines.append("%s\t%s\t%s\t%s" % (key[0], key[1], key[2], text))
    report.write("  LEN %d\n\n" % len(text))
report.close()

dst = os.path.join(base, "fix_r8b_g1.tsv")
io.open(dst, "w", encoding="utf-8", newline="").write("\n".join(out_lines) + "\n")

