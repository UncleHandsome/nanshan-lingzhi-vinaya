def load():
    rows = []
    with io.open(SRC, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line:
                continue
            rows.append(line.split("\t"))
    return rows[0], rows[1:]


def main():
    hdr, data = load()
    assert hdr[0] == "gid" and hdr[1] == "book", hdr[:3]
    # a few rows elsewhere in the report contain embedded newlines and are short;
    # every 02/03 row has exactly 13 fields.
    sel = [r for r in data if len(r) == 13 and r[1] in ("02_戒疏", "03_業疏")]
    print("selected rows:", len(sel))

    problems = []
    out_lines = []
    done = 0
    skipped = 0

    seen = set()
    for r in sel:
        gid, book, chunk, seg, cur = r[0], r[1], r[2], r[3], r[10]
        seen.add(gid)
        if gid in SKIPS:
            skipped += 1
            print("SKIP", gid, SKIPS[gid])
            continue
        if gid not in EDITS:
            problems.append("no edit entry for gid %s" % gid)
            skipped += 1
            continue
        new = cur
        for (old, rep, cnt) in EDITS[gid]:
            got = new.count(old)
            if got != cnt:
                problems.append("gid %s: expected %d occurrence(s) of %r, found %d" % (gid, cnt, old, got))
                continue
            new = new.replace(old, rep)
        if new == cur:
            problems.append("gid %s: no change produced" % gid)
            skipped += 1
            continue
        if "\t" in new or "\n" in new or "\r" in new:
            problems.append("gid %s: new contains tab/newline" % gid)
            continue
        if not new.strip():
            problems.append("gid %s: new empty" % gid)
            continue
        out_lines.append("%s\t%s\t%s\t%s" % (book, chunk, seg, new))
        done += 1

    for gid in EDITS:
        if gid not in seen:
            problems.append("edited gid not found in 02/03 selection: %s" % gid)

    if problems:
        print("--- PROBLEMS ---")
        for p in problems:
            print(p)
        sys.exit(1)

    payload = "\n".join(out_lines) + "\n"
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(payload)

    print("written", OUT)
    print("rows:", len(out_lines), "done:", done, "skipped:", skipped)


if __name__ == "__main__":
    main()
