def apply(gid, cur):
    ops = OPS[gid]
    if ops == "SKIP":
        return None, "skip", []
    log = []
    new = cur
    if ops == "TAIL":
        i = cur.find("此等淫處")
        if i < 0:
            return None, "skip", [("MISS", "tail")]
        new = cur[:i] + TAIL_0924
        return new, "ok", [("ok", "tail", len(cur) - i, len(TAIL_0924))]
    for op in ops:
        kind = op[0]
        if kind == "rep":
            old, rep = op[1], op[2]
            c = new.count(old)
            if c == 0:
                log.append(("MISS", old[:20]))
                continue
            new = new.replace(old, rep, 1)
            log.append(("ok", old[:20], c))
        elif kind == "repall":
            old, rep = op[1], op[2]
            c = new.count(old)
            new = new.replace(old, rep)
            log.append(("okall", old[:20], c))
        elif kind == "del":
            old = op[1]
            if old in new:
                new = new.replace(old, "", 1)
                log.append(("okdel", old[:20], 1))
            else:
                log.append(("MISS", old[:20]))
        elif kind == "prepend":
            new = op[1] + new
            log.append(("okpre", op[1][:20], 1))
        elif kind == "bracket":
            old = op[1]
            if "「" + old + "」" in new:
                new = new.replace("「" + old + "」", "〔" + old + "〕", 1)
                log.append(("okbr", old[:20], 1))
            else:
                log.append(("MISS", old[:20]))
    return new, "ok", log


rows_out = []
diag = []
ctx_report = []
for d in recs:
    gid = d["gid"]
    cur = d["current"]
    new, status, log = apply(gid, cur)
    diag.append("%-9s %-4s %s" % (gid, status, log))
    if new is None:
        continue
    if "\n" in new or "\t" in new:
        new = new.replace("\r", "").replace("\n", "")
    # context of first difference
    i = 0
    while i < min(len(cur), len(new)) and cur[i] == new[i]:
        i += 1
    ctx = "…" + cur[max(0, i - 25):i] + "【" + new[i:i + 40].replace("\n", "") + "】" + "…"
    if i >= min(len(cur), len(new)):
        ctx = "（無差異）"
    ctx_report.append("%-9s %s" % (gid, ctx))
    rows_out.append((d["book"], d["chunk"], d["seg"], new))

with open(BASE + r"\fix_qc.tsv", "w", encoding="utf-8", newline="") as f:
    for book, chunk, seg, new in rows_out:
        f.write("%s\t%s\t%s\t%s\n" % (book, chunk, seg, new))

