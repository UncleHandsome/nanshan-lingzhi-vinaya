def parse_auto(s):
    m = re.match(r"^將「(.+?)」改為「(.+?)」", s) or re.search(r"將「(.+?)」改為「(.+?)」", s)
    if m: return m.group(1), m.group(2)
    m = re.match(r"^「(.+?)」改為「(.+?)」", s) or re.search(r"「(.+?)」改為「(.+?)」", s)
    if m: return m.group(1), m.group(2)
    m = re.search(r"^(?:.*?)\s*(.+?)\s*->\s*(.+)$", s)
    if m and "->" in s: return m.group(1).strip(), m.group(2).strip()
    return None, None

