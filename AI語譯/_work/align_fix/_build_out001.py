# -*- coding: utf-8 -*-
"""Build out_001.json for align_fix batch 001 (sec 9 師資相攝).

Method: for each 記段 z, locate the 鈔段 c it comments on, using the 牒詞
(「二明攝受」「次明依止」「受法中」「第六標分」...) and the running order of
the 記 against the 鈔.  Result cross-checked paragraph by paragraph against
the full 鈔 section (TXT/01_四分律刪繁補闕行事鈔.txt) and the full 記
(TXT/資持記/04_上三.txt); assignments are monotone and every c is drawn from cand.
"""
import json, io, os, re

B = r"C:\Users\lionc\OneDrive\桌面\XW\三大部"
AD = os.path.join(B, "AI語譯", "_work", "align_fix")

d = json.load(io.open(os.path.join(AD, "001.json"), encoding="utf-8"))
items, cand = d["items"], d["cand"]
n, m = len(items), len(cand)

# 記段 -> 鈔段 index (0-based).  Derived by 牒詞 / 義理順序 analysis:
#   z0 -z3   : 篇題釋名 + 來意 + 彰非 + 篇意                     -> c0  佛法增益廣大…
#   z4 -z9   : 師名、資名、總相攝、六方禮、四心                    -> c1  問云何名師…
#   z10      : 「次明依止」牒 c2 科文，兼總科八人                   -> c2  二明依止法…
#   z11      : 八人（十誦七、五分八）                              -> c3  得不依止者八人…
#   z12-z14  : 須依止十種，末及「次正行中」總科                    -> c4  二須依止人十種…
#   z15-z17  : 共行七法                                          -> c6  初中七法者…
#   z18-z22  : 白事離過（八事、五分、十誦、僧祇、通白、善見）        -> c8  一白事離過者…
#   z23      : 「受法中」                                        -> c9  二受法者…
#   z24-z26  : 報恩法                                            -> c10 三報恩法…
#   z27      : 「二明攝受，標示中」七門、制意、得無師時節            -> c11 大門第二…
#   z28      : 五百問犯盜、不誦戒、第三列名                        -> c13 二得無師時節…
#   z29-z35  : 簡師德（諸師不同、選択、三千威儀）                    -> c14 三簡師德…
#   z36-z37  : 請師法                                            -> c15 四明請師法…
#   z38-z42  : 師攝受法（教誡、請意、斥非、五緣、王難）              -> c16 五師攝受法…
#   z43      : 老弟子法                                          -> c17 今次明老弟子法…
#   z44      : 「第六，標分中」                                   -> c18 六明治罰訶責法…
#   z45-z49  : 十五種過、善戒、五百問龍緣、雜含                     -> c19 初中《四分》十五種…
#   z50-z57  : 訶責法（自量、五法、涅槃三子、地持、大集）            -> c20 二明訶責法…
#   z58-z59  : 訶責非法                                          -> c21 三明訶責非法…
#   z60-z63  : 辭謝法                                            -> c22 四明辭謝法…
#   z64-z73  : 失師法（九種、約教失、問答、卷末）                   -> c23 七明失師法…
MAP = (
    [0]*4 + [1]*6 + [2] + [3] + [4]*3 + [6]*3 + [8]*5 + [9] + [10]*3 + [11]
    + [13] + [14]*7 + [15]*2 + [16]*5 + [17] + [18] + [19]*5 + [20]*8
    + [21]*2 + [22]*4 + [23]*10
)
assert len(MAP) == n == 74, (len(MAP), n)
assert all(0 <= c < m for c in MAP)
assert all(MAP[i] <= MAP[i+1] for i in range(n-1))

out = {"map": [{"z": it["z"], "c": MAP[i]} for i, it in enumerate(items)]}
io.open(os.path.join(AD, "out_001.json"), "w", encoding="utf-8").write(
    json.dumps(out, ensure_ascii=False, separators=(",", ":")))

# validation
back = json.load(io.open(os.path.join(AD, "out_001.json"), encoding="utf-8"))
mp = back["map"]
print("entries", len(mp), "== items", len(items), len(mp) == len(items))
print("z ok", [x["z"] for x in mp] == [it["z"] for it in items])
cs = [x["c"] for x in mp]
print("monotone", cs == sorted(cs), "| in cand", all(0 <= c < m for c in cs),
      "| distinct", len(set(cs)), "| front", cs[:12], "| back", cs[-10:])
