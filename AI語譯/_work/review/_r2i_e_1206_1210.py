def main():
    apply = '--apply' in sys.argv
    bad = 0
    for ch in (C, D):
        o = L.load_out(ch)
        for e in [x for x in edits if x['chunk'] == ch]:
            c = o['segs'][e['seg'] - 1].count(e['old'])
            if c != 1:
                bad += 1
                print('BAD count=%d %s#%d :: %s' % (c, ch, e['seg'], e['old'][:70]))
    print('edits=%d bad=%d' % (len(edits), bad))
    if bad:
        raise SystemExit('abort')
    if apply:
        for ch in (C, D):
            es = [x for x in edits if x['chunk'] == ch]
            if es:
                L.apply_edits(ch, es, note='r2 1181-1330')
        json.dump(edits, open(os.path.join(HERE, '_r2i_edits_1206_1210.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
