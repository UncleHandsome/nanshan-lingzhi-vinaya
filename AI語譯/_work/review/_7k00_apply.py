def main():
    raw = io.open(P, "rb").read().decode("utf-8")
    assert not raw.startswith("\ufeff"), "unexpected BOM"
    body = raw
    nl = "\r\n" if "\r\n" in body else "\n"
    parts = body.split(nl + nl)
    idx = [i for i, p in enumerate(parts) if p.strip()]
    if len(idx) != 82:
        sys.exit("unexpected paragraph count %d" % len(idx))

    orig_parts = list(parts)
    recs = []
    for seg, edits, note in EDITS:
        pi = idx[seg - 1]
        block = parts[pi]
        before = block
        for old, new in edits:
            c = block.count(old)
            if c != 1:
                sys.exit("FAIL seg %d count=%d: %r" % (seg, c, old[:40]))
            block = block.replace(old, new)
        parts[pi] = block
        sm = difflib.SequenceMatcher(None, before, block)
        ops = [(t, before[i1:i2], block[j1:j2])
               for t, i1, i2, j1, j2 in sm.get_opcodes() if t != "equal"]
        recs.append({"seg": seg, "note": note, "edits": len(edits),
                     "diff": [{"op": t, "old": a, "new": b} for t, a, b in ops]})

    changed = [i for i in range(len(parts)) if parts[i] != orig_parts[i]]
    print("segments to write:", [idx.index(i) + 1 for i in changed])

    os.makedirs(ARC, exist_ok=True)
    bak = os.path.join(ARC, "00_卷首_v.txt")
    if not os.path.exists(bak):
        shutil.copy2(P, bak)
        print("backup ->", bak)
    else:
        print("backup exists ->", bak)

    out = (nl + nl).join(parts)
    io.open(P, "wb").write(out.encode("utf-8"))
    with io.open(LOG, "a", encoding="utf-8") as f:
        for r in recs:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("wrote %d paragraphs, %d edited" % (len(parts), len(changed)))


if __name__ == "__main__":
    main()
