def find_in_books(needle):
    for f in glob.glob(os.path.join(B, 'TXT_分卷', '01_行事鈔', '*.txt')):
        s = io.open(f, encoding='utf-8').read().replace('\n', '')
        i = s.find(needle)
        if i >= 0:
            return s[i:i + 600]
    return ''

