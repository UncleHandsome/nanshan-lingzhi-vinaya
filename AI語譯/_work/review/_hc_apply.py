def main(dry):
    by = {}
    for c, p, old, new, note in EDITS:
        by.setdefault(c, []).append({"para": p, "old": old, "new": new, "note": note})
    n = 0
    for c in sorted(by):
        n += L.apply(c, by[c], dry=dry)
    print("EDITS applied =", n, "of", len(EDITS), "dry=", dry)
    if not dry:
        for c in sorted(by):
            print(c, L.resolve(c), "paras/lines", L.idx(c))


if __name__ == "__main__":
    main("--apply" not in sys.argv)
