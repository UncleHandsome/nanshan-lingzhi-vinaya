def counts(n):
    sp = os.path.join(REV, f"_7kq_spec_{n}.json")
    if n == 604:
        return 2, 0, 2
    if not os.path.exists(sp):
        return 0, 0, 0
    edits = json.loads(io.open(sp, encoding="utf-8").read())
    by = {}
    for e in edits:
        by.setdefault((e["chunk"], e["para"]), []).append(e["kind"])
    yi = sum(1 for k in by.values() if "義理" in k)
    run = len(by) - yi
    return len(by), yi, run

