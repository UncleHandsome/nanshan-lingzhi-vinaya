def clean(s):
    return s.replace('\r', '').replace('\n', '').replace('\t', '').strip()

def extract_68(group):
    sugg = group['rows'][0]['suggestion']
    marker = '可補譯為：'
    i = sugg.index(marker) + len(marker)
    rest = sugg[i:].lstrip()
    if rest.startswith('「'):
        j = rest.rfind('」')
        return clean(rest[1:j])
    raise SystemExit('cannot parse suggestion for 10a/23')

out_lines = []
log = []
applied_rows = 0
skipped_rows = 0
for g in groups:
    chunk, seg = g['key']
    cur = clean(g['current'])
    edits = D.get(g['key'])
    nr = len(g['rows'])
    if not edits:
        skipped_rows += nr
        log.append(('SKIP-NOFIX', chunk, seg, nr))
        continue
    if edits[0][0] == '@@WHOLE@@':
        new = extract_68(g)
        if not new:
            skipped_rows += nr
            log.append(('SKIP-NOSUGG', chunk, seg, nr))
            continue
        if new in cur:
            skipped_rows += nr
            log.append(('SKIP-APPLIED', chunk, seg, nr))
            continue
        out_lines.append((chunk, seg, new))
        applied_rows += nr
        log.append(('APPLIED-WHOLE', chunk, seg, nr))
        continue
    text = cur
    hits = 0
    for old, new in edits:
        o = clean(old)
        n = clean(new)
        cnt = text.count(o)
        if cnt == 1:
            text = text.replace(o, n)
            hits += 1
        elif cnt == 0:
            log.append(('  miss', chunk, seg, o[:20]))
        else:
            raise SystemExit('AMBIGUOUS %s %s %r' % (chunk, seg, o[:30]))
    if hits == 0:
        skipped_rows += nr
        log.append(('SKIP-APPLIED', chunk, seg, nr))
        continue
    if text == cur:
        skipped_rows += nr
        log.append(('SKIP-SAME', chunk, seg, nr))
        continue
    out_lines.append((chunk, seg, text))
    applied_rows += nr
    log.append(('APPLIED', chunk, seg, nr, hits))

for row in out_lines:
    assert '\t' not in row[2] and '\n' not in row[2]

keys = [(c, s) for c, s, _ in out_lines]
assert len(keys) == len(set(keys)), 'duplicate keys'

with io.open(OUT, 'w', encoding='utf-8', newline='') as f:
    for chunk, seg, text in out_lines:
        f.write('%s\t%s\t%s\t%s\n' % ('01_行事鈔', chunk, seg, text))

for e in log:
    print(e)
print('---')
print('output rows:', len(out_lines))
print('applied report rows:', applied_rows, 'skipped report rows:', skipped_rows, 'total:', applied_rows + skipped_rows)
