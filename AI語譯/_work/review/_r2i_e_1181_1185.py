def main():
    apply = '--apply' in sys.argv
    by_chunk = {}
    for e in edits:
        by_chunk.setdefault(e['chunk'], []).append(e)
    for chunk, es in by_chunk.items():
        o = L.load_out(chunk)
        segs = o['segs']
        print('== %s segs=%d edits=%d' % (chunk, len(segs), len(es)))
        # 檢查每條 old 在指定段恰出現一次
        ok = True
        for e in es:
            t = segs[e['seg'] - 1]
            c = t.count(e['old'])
            if c != 1:
                ok = False
                print('   BAD count=%d seg=%d :: %s' % (c, e['seg'], e['old'][:60]))
        if not ok:
            raise SystemExit('abort: bad old strings')
        if apply:
            L.apply_edits(chunk, es, note='r2 1181-1330')
            print('   applied; backup=%s' % L.backup(chunk))
    if apply:
        json.dump(edits, open(os.path.join(HERE, '_r2i_edits_1181_1185.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('total edits', len(edits))

main()
