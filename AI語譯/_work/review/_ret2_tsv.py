HDR = ["項次", "條目", "chunk", "行號", "段序", "核定", "動作",
       "原字串／原譯", "新字串／新譯", "對應原檔行（md 行號）", "依據／備註"]


def main():
    # 先算各檔段落起始行
    lineof = {}
    for ch in set(x[2] for x in T):
        p, t = L.load(ch)
        ps = L.paras(t)
        starts = []
        pos = 0
        for s in ps:
            starts.append(pos + 1)
            pos += s.count("\n") + 2
        lineof[ch] = starts

    out = []
    out.append("\t".join(HDR))
    for n, (mdl, label, ch, idx, verdict, action, old, new, note) in enumerate(T, 1):
        line = lineof[ch][idx - 1]
        name = {c: os.path.basename(L.path(c)) for c in lineof}[ch]
        row = [str(n), label, name, str(line), str(idx), verdict, action, old, new,
               "L%d" % mdl, note]
        assert len(row) == 11
        out.append("\t".join(row))
    dst = os.path.join(L.ROOT, "batch_qwen", "r7k_done", "ret2套用_資持記.tsv")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", dst, len(out) - 1, "rows")
    # 統計
    from collections import Counter
    print(Counter(x[4] for x in T))
    print(Counter(x[5] for x in T))


if __name__ == "__main__":
    main()
