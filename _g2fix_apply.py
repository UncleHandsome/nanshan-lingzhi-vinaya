rows = []
with open(SRC, encoding="utf-8") as f:
    for d in csv.DictReader(f, delimiter="\t"):
        if d["book"] == "03_業疏":
            rows.append(d)

by_gid = {d["gid"]: d for d in rows}
if len(by_gid) != len(rows):
    print("WARN duplicate gid")

ops_gids = [g for g, _ in OPS]
print("report rows:", len(rows), "ops rows:", len(OPS))
print("missing ops:", [g for g in by_gid if g not in ops_gids and g not in SKIP])
print("extra ops:", [g for g in ops_gids if g not in by_gid])

problems = []
results = []
skip_rows = []
for gid, d in [(d["gid"], d) for d in rows]:
    if gid in SKIP:
        # verify the quoted problem sentence really is absent
        skip_rows.append((gid, d["chunk"], d["seg"]))
        continue
    pairs = dict(OPS).get(gid)
    if not pairs:
        problems.append((gid, "NO OPS"))
        continue
    cur = d["current"]
    new = cur
    for old, rep in pairs:
        n = new.count(old)
        if n != 1:
            problems.append((gid, f"count={n} for {old[:40]}"))
            continue
        new = new.replace(old, rep)
    if "\t" in new or "\n" in new or "\r" in new:
        problems.append((gid, "BAD CHAR"))
    if new == cur:
        problems.append((gid, "NO CHANGE"))
    results.append((d["book"], d["chunk"], d["seg"], gid, cur, new))

print("problems:", problems)
print("fix rows:", len(results), "skip:", len(skip_rows))
print("skipped:", skip_rows)

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    for book, chunk, seg, gid, cur, new in results:
        f.write(f"{book}\t{chunk}\t{seg}\t{new}\n")

print("written", OUT)
